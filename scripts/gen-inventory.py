#!/usr/bin/env python3
"""Regenerate project-docs/FILE_INVENTORY.md from the real file tree. Run: python3 scripts/gen-inventory.py"""
import os, datetime
EXCL = {'node_modules', '.next', 'out', '.git', 'dist', 'build', 'coverage', '.wrangler'}
OUT = 'project-docs/FILE_INVENTORY.md'
rows = []
for d, ds, fs in os.walk('.'):
    ds[:] = [x for x in ds if x not in EXCL]
    for f in fs:
        p = os.path.join(d, f)[2:]
        if p == OUT: continue
        rows.append((p, os.path.splitext(f)[1].lstrip('.') or '-', sum(1 for _ in open(p, errors='ignore'))))
rows.sort()
c = lambda pred: sum(1 for r in rows if pred(r[0]))
test = c(lambda p: p.startswith('tests/'))
txt = f"# FILE INVENTORY\nGenerated by scripts/gen-inventory.py on {datetime.date.today()} from the real file tree (excludes {', '.join(sorted(EXCL))}). Per-file responsibilities: see ARCHITECTURE.md. 'Lines' is a raw line count.\n\n"
txt += "| Metric | Count |\n|---|---|\n"
for k, v in [('Total files (incl. this one)', len(rows) + 1), ('TS/TSX source (app, lib, components, functions)', c(lambda p: p.endswith(('.ts', '.tsx')) and not p.startswith('tests/'))), ('Components (components/)', c(lambda p: p.startswith('components/'))), ('Pages (page.tsx)', c(lambda p: p.endswith('page.tsx'))), ('Cloudflare Functions (functions/**.ts)', c(lambda p: p.startswith('functions/') and p.endswith('.ts') and 'tsconfig' not in p)), ('SQL migrations', c(lambda p: p.endswith('.sql'))), ('Test files', test), ('Markdown docs', c(lambda p: p.endswith('.md')) + 1), ('Public assets (public/)', c(lambda p: p.startswith('public/')))]:
    txt += f"| {k} | {v} |\n"
txt += "\n| Path | Type | Lines |\n|---|---|---|\n" + "".join(f"| {p} | {t} | {n} |\n" for p, t, n in rows)
txt += "\nStatus: all files IMPLEMENTED unless FEATURE_MATRIX says otherwise. Known unused file: components/Dropzone.tsx.\n"
open(OUT, 'w').write(txt)
print('files', len(rows) + 1)
